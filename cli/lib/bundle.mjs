// The vendor bundle of an episode: everything its page loads, generated from a
// resolved episode (project.mjs). The output is deterministic, so it doubles as
// the library part of the render hash.
//
//   vendor/avatars.js    data block + runtime files in bundle order
//   vendor/avatars.css   tokens as custom properties + core and scene CSS
//   vendor/gsap.min.js   GSAP
//   vendor/fonts/*.woff2 the theme's fonts
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { toCss } from "./tokens.mjs";

const JS_HEADER = "// Generated by `avatars vendor`. Do not edit; change the library or the project instead.\n";
const CSS_HEADER = "/* Generated by `avatars vendor`. Do not edit; change the library or the project instead. */\n";

export function dataOf(r) {
  return {
    tokens: r.tokens,
    format: r.format,
    brand: r.brand,
    icons: r.icons,
    cast: r.cast,
    bases: r.bases,
    parts: r.parts,
  };
}

export function bundleJs(r) {
  const data =
    "(function (global) {\n" +
    '  "use strict";\n' +
    "  const A = (global.Avatars = global.Avatars || {});\n" +
    `  A.data = ${JSON.stringify(dataOf(r))};\n` +
    '})(typeof window !== "undefined" ? window : globalThis);\n';
  const parts = [JS_HEADER, data];
  for (const f of r.js) parts.push(`\n// ---- ${f.label}\n`, readFileSync(f.path, "utf8"));
  return parts.join("");
}

export function bundleCss(r) {
  const parts = [CSS_HEADER, toCss(r.tokens)];
  for (const f of r.css) parts.push(`\n/* ---- ${f.label} */\n`, readFileSync(f.path, "utf8"));
  return parts.join("");
}

// [relative path, contents] in a fixed order.
export function bundleFiles(r) {
  return [
    ["avatars.js", bundleJs(r)],
    ["avatars.css", bundleCss(r)],
    ["gsap.min.js", readFileSync(r.gsap)],
    ...r.fonts.map((f) => [`fonts/${f.file}`, readFileSync(f.path)]),
  ];
}

export function writeVendor(dir, files) {
  const out = path.join(dir, "vendor");
  rmSync(out, { recursive: true, force: true });
  for (const [rel, body] of files) {
    const p = path.join(out, rel);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, body);
  }
  return out;
}
